//! Feature `ispdb`: compiles the ISPDB snapshot in `MAILAUTODETECT_ISPDB_DIR` (the `ispdb/*.xml`
//! directory of a pinned `thunderbird/autoconfig` checkout) into `$OUT_DIR/ispdb_table.rs`, using
//! this crate's own parser and mapper. A document that fails the XML parser fails the build (the
//! input is a pinned, hash-checked snapshot); one without an `emailProvider`, or without a usable
//! IMAP and SMTP server after validation, is left out.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::{env, fs, path::PathBuf};

#[allow(dead_code)]
#[path = "src/xml.rs"]
mod xml;

#[allow(dead_code)]
#[path = "src/config.rs"]
mod config;

use config::{ParseError, Sock};

fn main() {
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-changed=src/xml.rs");
    println!("cargo::rerun-if-changed=src/config.rs");
    if env::var_os("CARGO_FEATURE_ISPDB").is_none() {
        return;
    }
    println!("cargo::rerun-if-env-changed=MAILAUTODETECT_ISPDB_DIR");
    let dir =
        PathBuf::from(env::var_os("MAILAUTODETECT_ISPDB_DIR").expect(
            "feature ispdb: set MAILAUTODETECT_ISPDB_DIR to the snapshot's ispdb/ directory",
        ));
    println!("cargo::rerun-if-changed={}", dir.display());
    let mut names: Vec<String> = fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
        .map(|e| {
            e.expect("readdir")
                .file_name()
                .into_string()
                .expect("UTF-8 file name")
        })
        .filter(|n| n.ends_with(".xml"))
        .collect();
    names.sort();

    let mut providers = String::new();
    let mut count = 0u16;
    let mut domains: BTreeMap<String, u16> = BTreeMap::new();
    for name in &names {
        let body = fs::read(dir.join(name)).unwrap_or_else(|e| panic!("{name}: {e}"));
        let t = match config::parse_template(&body) {
            Ok(t) => t,
            Err(ParseError::Schema(_)) => continue,
            Err(e @ ParseError::Xml(_)) => {
                panic!("{name}: {e} (pinned ISPDB snapshot refused by the parser)")
            }
        };
        if !t.config.is_usable() {
            continue;
        }
        write!(providers, "    Provider {{ file: {name:?}, imap: &[").unwrap();
        for s in &t.config.imap {
            entry(&mut providers, s);
        }
        providers.push_str("], smtp: &[");
        for s in &t.config.smtp {
            entry(&mut providers, s);
        }
        providers.push_str("] },\n");
        let stem = name.trim_end_matches(".xml").to_ascii_lowercase();
        for d in t.domains.into_iter().chain([stem]) {
            if config::valid_host(&d) {
                domains.entry(d).or_insert(count);
            }
        }
        count = count.checked_add(1).expect("fewer than 65,536 providers");
    }

    let mut out = String::from(
        "// Generated by mailautodetect's build.rs from the ISPDB snapshot. Do not edit.\n",
    );
    writeln!(out, "static PROVIDERS: &[Provider] = &[\n{providers}];").unwrap();
    out.push_str("static DOMAINS: &[(&str, u16)] = &[\n");
    for (d, p) in &domains {
        writeln!(out, "    ({d:?}, {p}),").unwrap();
    }
    out.push_str("];\n");
    let path = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR")).join("ispdb_table.rs");
    fs::write(&path, out).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
}

fn entry(out: &mut String, s: &config::Server) {
    let sock = match s.sock {
        Sock::Ssl => "Ssl",
        Sock::StartTls => "StartTls",
        Sock::Plain => "Plain",
    };
    write!(
        out,
        "Entry {{ host: {:?}, port: {}, sock: Sock::{sock}, username: {:?}, oauth2: {} }}, ",
        s.host,
        s.port,
        s.username.as_deref().unwrap_or(""),
        s.oauth2
    )
    .unwrap();
}
